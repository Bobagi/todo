/**
 * 1) an explicit choice, 2) the first supported language the browser asks for
 * (navigator.languages covers "de,es,en" → es), 3) English.
 */
export function detectLang(nav = typeof navigator === "undefined" ? {} : navigator, store) {
  const ls = store || (typeof localStorage === "undefined" ? null : localStorage);
  const saved = (ls?.getItem(LANG_KEY) || "").toLowerCase();
  if (SUPPORTED.includes(saved)) return saved;
  const prefs =
    Array.isArray(nav.languages) && nav.languages.length
      ? nav.languages
      : [nav.language || ""];
  for (const p of prefs) {
    const two = String(p).slice(0, 2).toLowerCase();
    if (SUPPORTED.includes(two)) return two;
  }
  return "en";
}

let current = detectLang();
if (typeof document !== "undefined") document.documentElement.lang = current;

export const lang = () => current;

/** Look up a key, filling `{vars}`. Missing key → English → the key itself. */
export function t(key, vars) {
  let s = DICTS[current]?.[key] ?? DICTS.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}

export function setLang(code) {
  if (!SUPPORTED.includes(code) || code === current) return;
  localStorage.setItem(LANG_KEY, code);
  location.reload();
}

